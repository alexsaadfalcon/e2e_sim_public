"""
Package an `e2e.ml.dataset`-style radar corpus into a self-contained bundle an
outsider can use with **no access to this repository**: they get the frames, the
manifest, a numpy-only decode spec (`DATA_FORMAT.md`), attribution/licensing terms,
a checksum manifest, and a README spelling out the exact three commands (generate ->
train -> eval) against the bundle's own paths.

This module does not generate or re-encode any data -- it only copies/hardlinks
files that already exist under a `generate_dataset`/`chain_generate` manifest
directory (see `e2e.ml.dataset`'s "On-disk dataset layout" docstring) into a new
bundle directory, plus writes the four small text files above.

CLI
---
    python -m e2e.ml.export_corpus --manifest <path/to/manifest.json> --out <bundle_dir> \\
        [--link] [--dry-run]

`--link` hardlinks frame/manifest files into the bundle instead of copying them
(same volume only; falls back to a copy if the OS/filesystem refuses the link --
e.g. crossing a volume boundary) -- useful for a large corpus where a copy would
double disk usage. `--dry-run` prints the plan (file count, byte total, output
paths) and writes nothing, matching this repo's convention elsewhere (see
`e2e.ml.dataset --dry-run` / `e2e.environment.scenario_runner --dry-run`).
"""

