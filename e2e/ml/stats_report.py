def build_arg_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="python -m e2e.ml.stats_report",
        description="Statistical-validation reporter for e2e.ml radar dataset corpora.",
    )
    p.add_argument("--manifest", default=None, help="path to a generate_dataset manifest.json")
    p.add_argument("--out", default=None,
                   help="output markdown path (default: <manifest dir>/stats_report.md, or "
                        "./combined_stats_report.md for --compare)")
    p.add_argument("--tensor-sample", type=int, default=None, dest="tensor_sample",
                   help="optional tensor-level sample size per split (see collect_stats)")
    p.add_argument("--compare", nargs="+", default=None, metavar="MANIFEST",
                   help="compare multiple manifests' corpus stats (cross-tier table + "
                        "monotonicity notes); mutually exclusive with running a single report")
    return p


def main(argv: Optional[List[str]] = None) -> int:
    args = build_arg_parser().parse_args(argv)

    if args.compare:
        stats_list = [collect_stats(m, tensor_sample_per_split=args.tensor_sample) for m in args.compare]
        comparison = compare_tiers(stats_list)
        out_path = Path(args.out) if args.out else Path("combined_stats_report.md")
        write_comparison_report(comparison, out_path)
        print(f"wrote {out_path}")
        return 0

    if not args.manifest:
        print("either --manifest or --compare is required", file=sys.stderr)
        return 2

    stats = collect_stats(args.manifest, tensor_sample_per_split=args.tensor_sample)
    out_path = Path(args.out) if args.out else Path(args.manifest).parent / "stats_report.md"
    write_report(stats, out_path)
    print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
